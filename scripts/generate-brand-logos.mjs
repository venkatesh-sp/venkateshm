// Extracts the brand logos used by the portfolio from the tech-stack-icons package
// into a small TypeScript module, so the whole 700+ icon set is not bundled.
// Run with: yarn icons:brands
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const icons = JSON.parse(readFileSync(resolve(root, "node_modules/tech-stack-icons/icons.json"), "utf8"));

// Brand keys used in data/tech-icons.ts (IconName values).
const names = [
  "python",
  "django",
  "flask",
  "nodejs",
  "expressjs",
  "nextjs",
  "elixir",
  "heroku",
  "ec2",
  "aws",
  "docker",
  "mongodb",
  "swagger",
  "wordpress",
];

const logos = {};
for (const name of names) {
  const icon = icons[name];
  if (!icon) throw new Error(`Missing icon in tech-stack-icons: ${name}`);
  logos[name] = { light: icon.svg.light, dark: icon.svg.dark };
}

const body = Object.entries(logos)
  .map(
    ([name, { light, dark }]) =>
      `  ${JSON.stringify(name)}: { light: ${JSON.stringify(light)}, dark: ${JSON.stringify(dark)} },`,
  )
  .join("\n");

writeFileSync(
  resolve(root, "data/brand-logos.ts"),
  `// Generated by scripts/generate-brand-logos.mjs from the tech-stack-icons package. Do not edit by hand.\n` +
    `export interface BrandLogo {\n  light: string;\n  dark: string;\n}\n\nexport const brandLogos: Record<string, BrandLogo> = {\n${body}\n};\n`,
);
console.log(`Wrote ${names.length} brand logos to data/brand-logos.ts`);
